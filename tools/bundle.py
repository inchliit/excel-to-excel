"""Concatenate the deck's local scripts into js/deck.bundle.js (one request instead of ~47).
Run after editing any js/ file:  python3 tools/bundle.py   (tests/check-bundle.mjs fails if the bundle is stale)."""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIBS = ['js/lib/registry.js', 'js/lib/steps.js', 'js/lib/grid.js', 'js/lib/ui.js', 'js/lib/charts.js', 'js/lib/tryit.js']
TAIL = ['js/slides/static.js', 'js/lib/dev.js', 'js/lib/build.js']


def sources():
    tricks = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / 'js/tricks').glob('[0-9][0-9]-*.js'))
    anim = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / 'js/anim').glob('[0-9][0-9]-*.js'))
    return LIBS + tricks + anim + TAIL, set(tricks + anim)


def build():
    order, content = sources()
    out = ['/* deck.bundle.js: GENERATED by tools/bundle.py. Do not edit; edit the source files listed below. */']
    for rel in order:
        code = (ROOT / rel).read_text(encoding='utf-8').rstrip()
        # trick/anim files get their own scope so their helper names never collide
        out.append(f'\n/* ==== {rel} ==== */')
        out.append(f'(function () {{\n{code}\n}})();' if rel in content else code + '\n;')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    text = build()
    if '--print' in sys.argv:
        sys.stdout.write(text)
    else:
        (ROOT / 'js/deck.bundle.js').write_text(text, encoding='utf-8')
        print('js/deck.bundle.js:', len(text.encode('utf-8')), 'bytes')
